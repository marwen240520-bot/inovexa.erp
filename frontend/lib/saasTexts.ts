export const SAAS_TEXTS: Record<string, SaasTexts> = { fr, en, es, ar };

/** Textes SaaS dans la langue de l'interface (français si la langue n'est pas couverte). */
export function useSaasTexts(): SaasTexts {
  const { language } = useLanguage();
  return SAAS_TEXTS[language] || fr;
}

/** Remplace {cle} par sa valeur : fill("Essai : {time}", { time: "2 j" }). */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => (values[key] === undefined ? `{${key}}` : String(values[key])));
}

/** « 2 j 5 h », « 5 h 12 min », « 12 min ». */
export function formatRemaining(seconds: number | null | undefined, tx: SaasTexts): string {
  if (seconds === null || seconds === undefined) return "";
  const s = Math.max(0, Math.floor(seconds));
  if (s < 60) return tx.time.lessThanMinute;
  const d = Math.floor(s / 86400);
  const h = Math.floor((s % 86400) / 3600);
  const m = Math.floor((s % 3600) / 60);
  if (d > 0) return `${d} ${tx.time.d} ${h} ${tx.time.h}`;
  if (h > 0) return `${h} ${tx.time.h} ${String(m).padStart(2, "0")} ${tx.time.min}`;
  return `${m} ${tx.time.min}`;
}
