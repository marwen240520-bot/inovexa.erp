type Reply = { ok: boolean; status: number; data: any; message: string };

async function call(path: string, method: "GET" | "POST", body?: unknown): Promise<Reply> {
  try {
    const token = getToken();
    const res = await fetch(`${API_URL}${path}`, {
      method,
      headers: { "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const data = await res.json().catch(() => null);
    const raw = data?.message;
    const message = Array.isArray(raw) ? raw.join(" · ") : typeof raw === "string" ? raw : "";
    return { ok: res.ok, status: res.status, data, message };
  } catch {
    return { ok: false, status: 0, data: null, message: "" };
  }
}

const field: CSSProperties = {
  width: "100%", boxSizing: "border-box", padding: "10px 12px", borderRadius: 10, border: "1px solid var(--theme-border)",
  background: "var(--theme-surface)", color: "var(--theme-text)", fontSize: 15, outline: "none", minWidth: 0,
};

const button = (kind: "primary" | "ghost" | "danger", disabled?: boolean): CSSProperties => ({
  padding: "10px 16px", borderRadius: 10, fontSize: 14, fontWeight: 600, whiteSpace: "nowrap",
  cursor: disabled ? "not-allowed" : "pointer", opacity: disabled ? 0.6 : 1,
  ...(kind === "primary"
    ? { background: "var(--theme-primary, #4f46e5)", color: "#fff", border: "1px solid transparent" }
    : kind === "danger"
      ? { background: "transparent", color: "#dc2626", border: "1px solid #dc2626" }
      : { background: "transparent", color: "var(--theme-text)", border: "1px solid var(--theme-border)" }),
});

export interface TwoFactorCardProps {
  /** Langue de la carte ; par défaut celle de l'interface (l'administration est en français). */
  language?: Lang;
  /** Affiche « fortement recommandé » tant qu'elle n'est pas activée (comptes administrateurs). */
  recommended?: boolean;
  /** Fond de la carte : « nested » dans une carte du profil, « page » directement sur la page. */
  tone?: "nested" | "page";
  /** Prévenu après chaque activation ou désactivation réussie. */
  onChange?: (enabled: boolean) => void;
}

export default function TwoFactorCard({ language, recommended = false, tone = "nested", onChange }: TwoFactorCardProps) {
  const ui = useLanguage().language;
  const lang: Lang = (language || (ui === "en" || ui === "es" ? ui : "fr")) as Lang;
  const T = TEXTS[lang];

  const [enabled, setEnabled] = useState<boolean | null>(null);
  const [loadFailed, setLoadFailed] = useState(false);
  const [setup, setSetup] = useState<{ secret: string; qr: string; link: string } | null>(null);
  const [code, setCode] = useState("");
  const [password, setPassword] = useState("");
  const [asking, setAsking] = useState(false); // formulaire de désactivation ouvert
  const [busy, setBusy] = useState(false);
  const [problem, setProblem] = useState("");
  const [success, setSuccess] = useState("");
  const [copied, setCopied] = useState(false);

  const explain = useCallback((res: Reply): string => {
    if (res.status === 0) return T.network;
    if (res.status === 429) return T.tooMany;
    if (res.status === 401 && res.message !== "Mot de passe incorrect") return T.expired;
    return serverText(res.message, lang) || T.generic;
  }, [T, lang]);

  const load = useCallback(async () => {
    setLoadFailed(false);
    const res = await call("/auth/me", "GET");
    if (res.ok && res.data && typeof res.data.twoFactorEnabled === "boolean") {
      setEnabled(res.data.twoFactorEnabled);
      updateStoredTwoFactor(res.data.twoFactorEnabled);
    } else {
      setLoadFailed(true);
    }
  }, []);

  useEffect(() => { void load(); }, [load]);

  const reset = () => { setSetup(null); setCode(""); setPassword(""); setAsking(false); setProblem(""); setCopied(false); };
  const cleanCode = (value: string) => value.replace(/\D/g, "").slice(0, 6);
  const codeOk = /^\d{6}$/.test(code);

  const start = async () => {
    if (busy) return;
    setBusy(true); setProblem(""); setSuccess("");
    const res = await call("/auth/2fa/setup", "POST");
    setBusy(false);
    if (res.ok && res.data?.secret && res.data?.qrCodeDataUrl) {
      setSetup({ secret: String(res.data.secret), qr: String(res.data.qrCodeDataUrl), link: String(res.data.otpauthUrl || "") });
      setCode("");
    } else {
      setProblem(explain(res));
      if (res.status === 400) void load(); // déjà activée ailleurs : on remet l'état à jour
    }
  };

  const confirm = async () => {
    if (busy) return;
    if (!codeOk) { setProblem(T.badCode); return; }
    setBusy(true); setProblem("");
    const res = await call("/auth/2fa/enable", "POST", { code });
    setBusy(false);
    if (res.ok) {
      reset();
      setEnabled(true);
      updateStoredTwoFactor(true);
      setSuccess(T.activated);
      onChange?.(true);
    } else {
      setProblem(explain(res));
    }
  };

  const disable = async () => {
    if (busy) return;
    if (!password) { setProblem(T.needPassword); return; }
    if (!codeOk) { setProblem(T.badCode); return; }
    setBusy(true); setProblem("");
    const res = await call("/auth/2fa/disable", "POST", { password, code });
    setBusy(false);
    if (res.ok) {
      reset();
      setEnabled(false);
      updateStoredTwoFactor(false);
      setSuccess(T.disabled);
      onChange?.(false);
    } else {
      setProblem(explain(res));
    }
  };

  const copySecret = async () => {
    if (!setup) return;
    try { await navigator.clipboard.writeText(setup.secret); setCopied(true); window.setTimeout(() => setCopied(false), 2500); } catch { /* presse-papiers indisponible */ }
  };

  const onEnter = (action: () => void) => (e: React.KeyboardEvent) => { if (e.key === "Enter") { e.preventDefault(); action(); } };
  const grouped = setup ? setup.secret.replace(/(.{4})/g, "$1 ").trim() : "";

  return (
    <section
      style={{
        border: "1px solid var(--theme-border)", borderRadius: 14, padding: 16,
        background: tone === "nested" ? "var(--theme-surface-hover, var(--theme-surface))" : "var(--theme-surface)",
        color: "var(--theme-text)",
      }}
    >
      <header style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 10, flexWrap: "wrap", marginBottom: 8 }}>
        <h3 style={{ margin: 0, fontSize: 16, fontWeight: 700 }}>{T.title}</h3>
        {enabled !== null && (
          <span
            style={{
              padding: "3px 10px", borderRadius: 999, fontSize: 12, fontWeight: 700,
              background: enabled ? "rgba(16,185,129,.16)" : "rgba(107,114,128,.16)", color: enabled ? "#059669" : "var(--theme-text-secondary)",
            }}
          >
            {enabled ? T.on : T.off}
          </span>
        )}
      </header>
      <p style={{ margin: "0 0 12px", fontSize: 14, lineHeight: 1.5, color: "var(--theme-text-secondary)" }}>{T.lead}</p>

      {enabled === null && !loadFailed && <p style={{ margin: 0, fontSize: 14, color: "var(--theme-text-secondary)" }}>{T.loading}</p>}
      {loadFailed && (
        <div style={{ display: "flex", alignItems: "center", gap: 10, flexWrap: "wrap" }}>
          <span style={{ fontSize: 14, color: "#dc2626" }}>{T.loadError}</span>
          <button type="button" style={button("ghost")} onClick={() => void load()}>{T.retry}</button>
        </div>
      )}

      {/* ── Désactivée : bouton de départ, puis configuration ── */}
      {enabled === false && !setup && (
        <div>
          {recommended && <p style={{ margin: "0 0 10px", fontSize: 13, fontWeight: 600, color: "#b45309" }}>{T.recommended}</p>}
          <button type="button" style={button("primary", busy)} disabled={busy} onClick={start}>{busy ? "…" : T.start}</button>
        </div>
      )}

      {enabled === false && setup && (
        <div style={{ display: "grid", gap: 14 }}>
          <p style={{ margin: 0, fontSize: 14, lineHeight: 1.5 }}><strong>1.</strong> {T.step1}</p>
          <div>
            <p style={{ margin: "0 0 8px", fontSize: 14, lineHeight: 1.5 }}><strong>2.</strong> {T.step2}</p>
            <div style={{ display: "flex", gap: 16, flexWrap: "wrap", alignItems: "center" }}>
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={setup.qr} alt={T.qrAlt} width={176} height={176} style={{ background: "#fff", padding: 8, borderRadius: 10, border: "1px solid var(--theme-border)" }} />
              <div style={{ minWidth: 0, flex: "1 1 220px" }}>
                <code
                  style={{
                    display: "block", padding: "8px 10px", borderRadius: 8, border: "1px dashed var(--theme-border)", background: "var(--theme-surface)",
                    fontSize: 15, letterSpacing: 1, wordBreak: "break-all", userSelect: "all",
                  }}
                >
                  {grouped}
                </code>
                <div style={{ display: "flex", gap: 8, flexWrap: "wrap", alignItems: "center", marginTop: 8 }}>
                  <button type="button" style={button("ghost")} onClick={copySecret}>{copied ? T.copied : T.copy}</button>
                  {setup.link.startsWith("otpauth://") && (
                    <a href={setup.link} style={{ fontSize: 13, color: "var(--theme-primary, #4f46e5)" }}>{T.sameDevice}</a>
                  )}
                </div>
              </div>
            </div>
          </div>
          <div>
            <label htmlFor="tfa-code" style={{ display: "block", margin: "0 0 8px", fontSize: 14 }}><strong>3.</strong> {T.step3}</label>
            <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
              <input
                id="tfa-code"
                inputMode="numeric"
                autoComplete="one-time-code"
                placeholder="123456"
                aria-label={T.code}
                value={code}
                onChange={(e) => setCode(cleanCode(e.target.value))}
                onKeyDown={onEnter(confirm)}
                style={{ ...field, maxWidth: 180, letterSpacing: 4, textAlign: "center", fontSize: 18 }}
              />
              <button type="button" style={button("primary", busy || !codeOk)} disabled={busy || !codeOk} onClick={confirm}>{busy ? "…" : T.confirm}</button>
              <button type="button" style={button("ghost")} onClick={reset}>{T.cancel}</button>
            </div>
          </div>
        </div>
      )}

      {/* ── Activée : rappel, puis désactivation protégée ── */}
      {enabled === true && !asking && (
        <div style={{ display: "grid", gap: 10 }}>
          <p style={{ margin: 0, fontSize: 13, lineHeight: 1.5, color: "var(--theme-text-secondary)" }}>{T.keepAccess}</p>
          <div>
            <button type="button" style={button("danger")} onClick={() => { setAsking(true); setProblem(""); setSuccess(""); }}>{T.disableTitle}</button>
          </div>
        </div>
      )}

      {enabled === true && asking && (
        <div style={{ display: "grid", gap: 10 }}>
          <p style={{ margin: 0, fontSize: 14, lineHeight: 1.5 }}>{T.disableHelp}</p>
          <input
            type="password"
            autoComplete="current-password"
            placeholder={T.password}
            aria-label={T.password}
            value={password}
            onChange={(e) => setPassword(e.target.value)}
            onKeyDown={onEnter(disable)}
            style={{ ...field, maxWidth: 360 }}
          />
          <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
            <input
              inputMode="numeric"
              autoComplete="one-time-code"
              placeholder="123456"
              aria-label={T.code}
              value={code}
              onChange={(e) => setCode(cleanCode(e.target.value))}
              onKeyDown={onEnter(disable)}
              style={{ ...field, maxWidth: 180, letterSpacing: 4, textAlign: "center", fontSize: 18 }}
            />
            <button type="button" style={button("danger", busy)} disabled={busy} onClick={disable}>{busy ? "…" : T.disable}</button>
            <button type="button" style={button("ghost")} onClick={reset}>{T.cancel}</button>
          </div>
        </div>
      )}

      {problem && <p role="alert" style={{ margin: "12px 0 0", fontSize: 14, fontWeight: 600, color: "#dc2626" }}>{problem}</p>}
      {success && !problem && <p role="status" style={{ margin: "12px 0 0", fontSize: 14, fontWeight: 600, color: "#059669" }}>{success}</p>}
    </section>
  );
}
